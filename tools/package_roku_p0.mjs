import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {build, readZip, sha256} from './roku_visual_lab.mjs';
const root='platforms/roku-lab-visual';
const previous=JSON.parse(await fs.readFile('docs/roku/p0-20261108/catalog-before.json'));
const current=JSON.parse(await fs.readFile(`${root}/catalog/commercial-lab-merged.json`));
assert.equal(previous.length,607);
assert.equal(current.length,608);
assert.equal(new Set(current.map(c=>c.id)).size,current.length);
for(const old of previous){
 const row=current.find(c=>c.id===old.id); assert(row,`lost ID ${old.id}`);
 const expected={...old};
 if(old.name==='Globo') expected.url='http://79.127.238.228:14173/';
 assert.deepEqual(row,expected,`unexpected catalog change ${old.id}`);
}
assert.equal(current.filter(c=>c.group==='Esportes')[0].name,'CazéTV');
assert.equal(current.find(c=>c.name==='History (Brazil) (720p)').url,'http://170.83.16.50/HISTORY/index.m3u8');
const account=await fs.readFile(`${root}/components/Account.brs`,'utf8');
assert(account.includes('if activateManualPhysicalLabAccess() then return'));
assert(account.includes('if m.physicalLabManual = true then return m.authorized'));
const manual=account.slice(account.indexOf('function activateManualPhysicalLabAccess()'));
for(const marker of ['cfg.scope <> "roku_lab_only"','integration.enabled <> false','m.physicalLabManual = true','m.authorized = true']) assert(manual.includes(marker),marker);
assert(!manual.includes('billingExpiry.control = "start"'));
const home=await fs.readFile(`${root}/components/HomeScene.brs`,'utf8');
assert(home.includes('"Não testados"'));
assert(home.includes('categoryMatches = not tested'));
assert(!home.includes('lcase(trim('));
for(const config of ['auth','central-access','lab-access']) assert.equal(JSON.parse(await fs.readFile(`${root}/config/${config}.json`)).enabled,false);
const target=process.argv[2] || 'build/RochaPlus-Roku-LAB-P0-0.6.11-20261108.zip';
const result=await build(root,target,{excludeProvisionalCovers:true,onlyMappedLogoFiles:true});
const files=readZip(await fs.readFile(target));
assert.equal(JSON.parse(files['catalog/commercial-lab-merged.json']).length,608);
const covers=JSON.parse(files['config/cover-map.json']);
assert.equal(Object.keys(covers).length,578);
for(const uri of Object.values(covers)) assert(files[uri.replace('pkg:/','')],`missing artwork ${uri}`);
assert.equal(JSON.parse(files['config/physical-lab-access.json']).mode,'physical_test_manual');
assert.match(files.manifest.toString(),/build_version=11/);
const second=await build(root,'/tmp/roku-p0-repeat.zip',{excludeProvisionalCovers:true,onlyMappedLogoFiles:true});
assert.equal(second.sha256,result.sha256,'deterministic package');
const evidence={...result,catalog:608,priorIdsPreserved:607,removed:0,covers:578,repeatable:true,integrationsEnabled:false,playback:'manual physical LAB enabled by P0 order; hardware playback not yet validated',sourceCatalogSha256:sha256(await fs.readFile(`${root}/catalog/commercial-lab-merged.json`))};
await fs.writeFile('docs/roku/p0-20261108/package-evidence.json',JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify(evidence));
